"""Builds scripts/pixel_font.gd: a small bitmap font ("Pulse Pixel") for retro labels.
Glyphs are rasterised 1-bit (no smoothing) from DejaVu Sans Bold (free licence, renamed),
packed into one atlas, and embedded as base64 so the game builds the FontFile in code
(no import step, works the same in the editor, headless and the APK).
Run: python pixelfont.py ../godot/pulse_v4/scripts/pixel_font.gd
"""
import sys, base64, io
from PIL import Image, ImageDraw, ImageFont

SRC = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
PX = 11
font = ImageFont.truetype(SRC, PX)
asc, desc = font.getmetrics()
CH = [chr(c) for c in range(32, 127)]
glyphs = []
for ch in CH:
    cell = Image.new('L', (PX * 2, asc + desc + 2), 0)
    d = ImageDraw.Draw(cell)
    d.fontmode = '1'
    d.text((2, 0), ch, font=font, fill=255)
    bb = cell.getbbox()
    adv = int(round(font.getlength(ch)))
    if bb is None:
        glyphs.append((ch, None, 0, 0, adv))
        continue
    g = cell.crop(bb)
    glyphs.append((ch, g, bb[0] - 2, bb[1], adv))
# pack into rows
W = 256
x = y = 2
row_h = 0
places = []
for ch, g, xo, yo, adv in glyphs:
    if g is None:
        places.append((ch, 0, 0, 0, 0, xo, yo, adv))
        continue
    w, h = g.size
    if x + w + 3 > W:
        x = 2
        y += row_h + 3
        row_h = 0
    places.append((ch, x, y, w, h, xo, yo, adv))
    x += w + 3
    row_h = max(row_h, h)
H = y + row_h + 3
H = 1 << (H - 1).bit_length()
atlas = Image.new('LA', (W, H), (255, 0))
for (ch, gx, gy, w, h, xo, yo, adv), (_, g, _, _, _) in zip(places, glyphs):
    if g is not None:
        a = g.point(lambda v: 255 if v > 127 else 0)
        atlas.paste(Image.merge('LA', (Image.new('L', g.size, 255), a)), (gx, gy))
buf = io.BytesIO()
atlas.convert('RGBA').save(buf, 'PNG')
b64 = base64.b64encode(buf.getvalue()).decode()
rows = ',\n\t'.join('%d: [%d, %d, %d, %d, %d, %d, %d]' % (ord(ch), gx, gy, w, h, xo, yo, adv) for ch, gx, gy, w, h, xo, yo, adv in places)
out = '''extends RefCounted
# "Pulse Pixel" - a small bitmap font for retro labels (overhead text, signs, game log).
# Generated by gen/pixelfont.py: glyphs rasterised 1-bit from DejaVu Sans Bold (free licence).
# Built in code, so it works the same everywhere. Draw it at multiples of %(px)d px
# (%(px)d, %(px2)d, %(px3)d) with nearest filtering for crisp pixels.

const SIZE := %(px)d
const ASCENT := %(asc)d
const DESCENT := %(desc)d
const GLYPHS := {
\t%(rows)s
}
const ATLAS := "%(b64)s"

static var _font: FontFile = null


static func font() -> FontFile:
\tif _font != null:
\t\treturn _font
\tvar img := Image.new()
\timg.load_png_from_buffer(Marshalls.base64_to_raw(ATLAS))
\tvar f := FontFile.new()
\tf.fixed_size = SIZE
\tf.fixed_size_scale_mode = TextServer.FIXED_SIZE_SCALE_INTEGER_ONLY
\tf.antialiasing = TextServer.FONT_ANTIALIASING_NONE
\tvar sz := Vector2i(SIZE, 0)
\tf.set_cache_ascent(0, SIZE, ASCENT)
\tf.set_cache_descent(0, SIZE, DESCENT)
\tf.set_texture_image(0, sz, 0, img)
\tfor code in GLYPHS:
\t\tvar g: Array = GLYPHS[code]
\t\tf.set_glyph_advance(0, SIZE, code, Vector2(g[6], 0))
\t\tf.set_glyph_offset(0, sz, code, Vector2(g[4], g[5] - ASCENT))
\t\tf.set_glyph_size(0, sz, code, Vector2(g[2], g[3]))
\t\tf.set_glyph_uv_rect(0, sz, code, Rect2(g[0], g[1], g[2], g[3]))
\t\tf.set_glyph_texture_idx(0, sz, code, 0)
\t_font = f
\treturn f
''' % {'px': PX, 'px2': PX * 2, 'px3': PX * 3, 'asc': asc, 'desc': desc, 'rows': rows, 'b64': b64}
open(sys.argv[1], 'w').write(out)
print('pixel font: %d glyphs, atlas %dx%d, ascent %d' % (len(places), W, H, asc))
